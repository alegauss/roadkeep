// The documentation area, at https://alegauss.github.io/roadkeep/docs/.
//
// Why an area at all: the README is the only prose this project publishes for a person and it
// is one file, so a link to any part of it is a link to the whole thing — and everything
// narrower (`--help`, `explain`, `config`, the skill) answers only from an installed copy.
// Evaluation comes before installation, so those are the reads adoption gates (RK1398).
//
// Why a second build rather than more sections in the pitch next door: that page is one
// scroll, laid out once, with no sidebar, no per-page contents and no search. Starlight is
// those three and indexes them at build time, so nothing here runs — which is the only shape
// this project's non-goal against a server allows.
//
// Three joins to the build next door, and none of them is remembered: `tests/test_area.py`
// reads this file and asserts each against what declares it elsewhere.
import { defineConfig } from "astro/config";
import starlight from "@astrojs/starlight";

// JOIN 1 — the base. GitHub Pages derives the site root from the repository name, so it is
// `/roadkeep/` and this area is one segment under it. Astro rewrites the links it generates
// and NOT the ones typed by hand, so an absolute href written into a page drops the prefix
// and 404s in production alone.
const BASE = "/roadkeep/docs";

// JOIN 2 — the output. The pitch next door builds to `site/dist/` and this area builds into a
// subdirectory of it, because the deploy uploads that one directory and nothing else: an area
// that wrote anywhere outside it would be a half of the site no publish carries.
//
// Astro empties outDir before it writes, and `vite build` empties `dist/` — which is why this
// build runs *last* in the site's `build` script. Reordered, it is deleted by the step after
// it, and the deploy goes green with the whole area missing.
//
// Nothing it writes is committed — the root .gitignore holds that, and the workflow that
// publishes the site is what runs this build. A generated tree in the repository would be a
// second answer to what the site is, and the stale one whenever somebody forgets to rebuild.
const OUT_DIR = "../dist/docs";

export default defineConfig({
  site: "https://alegauss.github.io",
  base: BASE,
  outDir: OUT_DIR,

  integrations: [
    starlight({
      title: "roadkeep",
      description:
        "How the tool works: the schema at insertion, the gate behind it, and what a session is charged for asking.",
      // Pagefind, indexed at build time — the reason search here needs no service to be up and
      // no account to exist, which is the same constraint the whole area is built under.
      pagefind: true,
      social: [
        { icon: "github", label: "GitHub", href: "https://github.com/alegauss/roadkeep" },
      ],
      customCss: ["./src/styles/area.css"],
      // JOIN 3 — the navigation. Autogenerated per directory rather than listed page by page:
      // a reference page is generated from this package (RK1402, RK1403, RK1404), so a hand
      // written sidebar entry would be the one thing about a generated page that is not
      // generated, and it would go missing exactly when a verb is added.
      sidebar: [
        // These four come before the reference because they are the reads an adopter needs
        // first, in the order they need them: the system the verbs act on (RK1407), the run
        // they will follow (RK1406), the file they will then write (RK1404), and what a
        // session receives once it is installed (RK1405). Named as links rather than
        // autogenerated, each being one page and not a directory.
        { label: "The model", link: "/model/" },
        { label: "Adopting", link: "/adopting/" },
        { label: "Configuration", link: "/configuration/" },
        { label: "In a session", link: "/session/" },
        { label: "Reference", items: [{ autogenerate: { directory: "reference" } }] },
        // A hundred-odd codes, grouped by the family the gate prints them under and collapsed:
        // the reader who wants one of these arrives from a search engine or from a failed job
        // with the code in hand, so this list is for browsing and never the way in (RK1403).
        {
          label: "Findings",
          collapsed: true,
          items: [{ autogenerate: { directory: "findings", collapsed: true } }],
        },
      ],
      // No "edit this page": the footer already links the repository, and a second link per
      // page is a claim about a contribution flow this project has not written down.
      editLink: {},
      lastUpdated: true,
    }),
  ],
});
